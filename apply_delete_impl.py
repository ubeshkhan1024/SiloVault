"""Apply B1.5 quarantine/restore/cleanup to google_drive.py."""
path = r"c:\Projects\SiloVault\backend\storage\google_drive.py"
with open(path, "rb") as f:
    data = f.read()

# Extract the exact old block from the file to guarantee a match
start = data.find(b"    def quarantine(self, provider_file_id: str) -> str:")
end = data.find(b"\r\n    # -----------------------------------------------------------------------\r\n    # Internal helpers", start)
old_block = data[start:end]

print(f"Found old block at {start}, length={len(old_block)}")
print("Old block repr:", repr(old_block[:150]))

new_lines = []
# quarantine
new_lines.append(b"    def quarantine(self, provider_file_id: str) -> str:")
new_lines.append(b'        if not isinstance(provider_file_id, str) or not provider_file_id.strip():')
new_lines.append(b'            raise StorageNotFoundError(')
new_lines.append(b'                provider_file_id or "",')
new_lines.append(b'                provider="GOOGLE_DRIVE",')
new_lines.append(b'            )')
new_lines.append(b'        if self._drive_service is None:')
new_lines.append(b'            raise StorageAuthenticationError(')
new_lines.append(b'                detail="Google Drive adapter is not authenticated. Call authenticate() first.",')
new_lines.append(b'                provider="GOOGLE_DRIVE",')
new_lines.append(b'            )')
new_lines.append(b'        try:')
new_lines.append(b'            self._drive_service.files()')
new_lines.append(b'            .update(')
new_lines.append(b'                fileId=provider_file_id,')
new_lines.append(b'                body={"trashed": True},')
new_lines.append(b'            )')
new_lines.append(b'            .execute()')
new_lines.append(b'        except HttpError as exc:')
new_lines.append(b'            raise self._map_drive_error(exc)')
new_lines.append(b'        return provider_file_id')
new_lines.append(b'')
# restore
new_lines.append(b'    def restore(self, quarantine_id: str) -> ProviderFileRecord:')
new_lines.append(b'        if not isinstance(quarantine_id, str) or not quarantine_id.strip():')
new_lines.append(b'            raise StorageNotFoundError(')
new_lines.append(b'                quarantine_id or "",')
new_lines.append(b'                provider="GOOGLE_DRIVE",')
new_lines.append(b'            )')
new_lines.append(b'        if self._drive_service is None:')
new_lines.append(b'            raise StorageAuthenticationError(')
new_lines.append(b'                detail="Google Drive adapter is not authenticated. Call authenticate() first.",')
new_lines.append(b'                provider="GOOGLE_DRIVE",')
new_lines.append(b'            )')
new_lines.append(b'        try:')
new_lines.append(b'            self._drive_service.files()')
new_lines.append(b'            .update(')
new_lines.append(b'                fileId=quarantine_id,')
new_lines.append(b'                body={"trashed": False},')
new_lines.append(b'            )')
new_lines.append(b'            .execute()')
new_lines.append(b'            response = (')
new_lines.append(b'                self._drive_service.files()')
new_lines.append(b'                .get(')
new_lines.append(b'                    fileId=quarantine_id,')
new_lines.append(b'                    fields="id,name,mimeType,size,modifiedTime,md5Checksum",')
new_lines.append(b'                )')
new_lines.append(b'                .execute()')
new_lines.append(b'            )')
new_lines.append(b'        except HttpError as exc:')
new_lines.append(b'            raise self._map_drive_error(exc)')
new_lines.append(b'        file_id = response.get("id")')
new_lines.append(b'        if not isinstance(file_id, str) or not file_id:')
new_lines.append(b'            raise StorageInvalidResponseError(')
new_lines.append(b'                body="Drive API restore get-response missing id",')
new_lines.append(b'                status_code=None,')
new_lines.append(b'                provider="GOOGLE_DRIVE",')
new_lines.append(b'            )')
new_lines.append(b'        return ProviderFileRecord(')
new_lines.append(b'            provider_file_id=file_id,')
new_lines.append(b'            name=response.get("name", quarantine_id),')
new_lines.append(b'            logical_path=f"/{file_id}",')
new_lines.append(b'            mime_type=response.get("mimeType", "application/octet-stream"),')
new_lines.append(b'            size_bytes=int(response.get("size", 0)) if response.get("size") else 0,')
new_lines.append(b'            sha256=None,')
new_lines.append(b'            provider_metadata={')
new_lines.append(b'                "md5_checksum": response.get("md5Checksum"),')
new_lines.append(b'                "web_view_link": f"https://drive.google.com/file/d/{file_id}/view",')
new_lines.append(b'                "web_content_link": f"https://drive.google.com/uc?id={file_id}&export=download",')
new_lines.append(b'            },')
new_lines.append(b'            modified_at=_parse_drive_timestamp(response.get("modifiedTime")),')
new_lines.append(b'        )')
new_lines.append(b'')
# cleanup
new_lines.append(b'    def cleanup(self, quarantine_id: str) -> None:')
new_lines.append(b'        if not isinstance(quarantine_id, str) or not quarantine_id.strip():')
new_lines.append(b'            raise StorageNotFoundError(')
new_lines.append(b'                quarantine_id or "",')
new_lines.append(b'                provider="GOOGLE_DRIVE",')
new_lines.append(b'            )')
new_lines.append(b'        if self._drive_service is None:')
new_lines.append(b'            raise StorageAuthenticationError(')
new_lines.append(b'                detail="Google Drive adapter is not authenticated. Call authenticate() first.",')
new_lines.append(b'                provider="GOOGLE_DRIVE",')
new_lines.append(b'            )')
new_lines.append(b'        try:')
new_lines.append(b'            self._drive_service.files()')
new_lines.append(b'            .delete(fileId=quarantine_id)')
new_lines.append(b'            .execute()')
new_lines.append(b'        except HttpError as exc:')
new_lines.append(b'            raise self._map_drive_error(exc)')
new_lines.append(b'        except Exception as exc:')
new_lines.append(b'            raise StorageUnavailableError(')
new_lines.append(b'                detail=f"Failed to cleanup quarantined file from Google Drive: {exc}",')
new_lines.append(b'                provider="GOOGLE_DRIVE",')
new_lines.append(b'            ) from exc')

new_block = b"\r\n".join(new_lines) + b"\r\n"

assert old_block in data, "Extracted old block not found in file!"
data = data.replace(old_block, new_block, 1)
with open(path, "wb") as f:
    f.write(data)
print("Implementation applied successfully")
